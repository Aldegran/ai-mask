class SSD1315:
    WIDTH = 64
    HEIGHT = 32
    PAGES = HEIGHT // 8

    def __init__(self, rst_pin=8):
        # We assume no native RST pin binding via python in this simple port unless gpio is added
        self.rst = rst_pin
        self.rotation = 0
        self.flip_x = False
        self.flip_y = False
        self.buffer = bytearray(self.WIDTH * self.PAGES)
        self.bus = smbus.SMBus(1)
        self.addr = 0x3C
        self.scroll_lock = threading.Lock()
        self.run_lock = threading.Lock()
        self._icons = {}
        self._blink_thread_started = False

    def command(self, cmd):
        try:
            self.bus.write_byte_data(self.addr, 0x00, cmd)
        except OSError:
            pass

    def data(self, d):
        try:
            self.bus.write_byte_data(self.addr, 0x40, d)
        except OSError:
            pass

    def begin(self):
        # Note: Hardware reset logic normally requires GPIO. 
        # Skipping RST pin toggle for I2C test.
        self.command(0xae)
        self.command(0xd5)
        self.command(0x80)
        self.command(0xa8)
        self.command(0x27)
        self.command(0xd3)
        self.command(0x00)
        self.command(0xad)
        self.command(0x30)
        self.command(0x8d)
        self.command(0x14)
        self.command(0x40)
        self.command(0xa6)
        self.command(0xa4)
        self.command(0xa1)
        self.command(0xc8)
        self.command(0xda)
        self.command(0x12)
        self.command(0x81)
        self.command(0xaf)
        self.command(0xd9)
        self.command(0x22)
        self.command(0xdb)
        self.command(0x20)
        self.command(0xaf)
        self.clear()
        self.display()

    def clear(self):
        for i in range(len(self.buffer)):
            self.buffer[i] = 0x00

    def fill(self, color):
        for i in range(len(self.buffer)):
            self.buffer[i] = 0xff if color else 0x00

    def setRotation(self, r):
        self.rotation = r & 3

    def setFlip(self, flip_x, flip_y):
        self.flip_x = bool(flip_x)
        self.flip_y = bool(flip_y)

    def setBrightness(self, level):
        self.command(0x81)
        self.command(level)

    def sleep(self, en):
        self.command(0xAE if en else 0xAF)

    def drawPixel(self, x, y, color):
        logical_width = self.WIDTH if self.rotation % 2 == 0 else self.HEIGHT
        logical_height = self.HEIGHT if self.rotation % 2 == 0 else self.WIDTH

        if getattr(self, 'flip_x', False):
            x = logical_width - 1 - x
        if getattr(self, 'flip_y', False):
            y = logical_height - 1 - y

        orig_x, orig_y = x, y
        if self.rotation == 1:
            x, y = orig_y, self.WIDTH - 1 - orig_x
        elif self.rotation == 2:
            x, y = self.WIDTH - 1 - orig_x, self.HEIGHT - 1 - orig_y
        elif self.rotation == 3:
            x, y = self.HEIGHT - 1 - orig_y, orig_x

        if x < 0 or x >= self.WIDTH or y < 0 or y >= self.HEIGHT:
            return

        i = x + (y // 8) * self.WIDTH
        m = 1 << (y % 8)

        if color == 2:
            self.buffer[i] ^= m
        elif color:
            self.buffer[i] |= m
        else:
            self.buffer[i] &= ~m

    def drawRect(self, x0, y0, x1, y1, fill=False, color=1):
        if x1 < x0:
            x0, x1 = x1, x0
        if y1 < y0:
            y0, y1 = y1, y0

        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                edge = (x == x0 or x == x1 or y == y0 or y == y1)
                if fill or edge:
                    self.drawPixel(x, y, color)

    def _blink_loop(self):
        while True:
            time.sleep(0.5)
            needs_update = False
            with self.scroll_lock:
                for icon_id, icon in list(self._icons.items()):
                    if icon['blink'] == 2:
                        icon['visible'] = not icon['visible']
                        self.drawRect(icon['x'], icon['y'], icon['x'] + icon['w'] - 1, icon['y'] + icon['h'] - 1, fill=True, color=0)
                        if icon['visible']:
                            self._renderBitmap(icon['x'], icon['y'], icon['bmp'], icon['w'], icon['h'], icon['invert'])
                        needs_update = True
                if needs_update:
                    self.display()

    def _renderBitmap(self, x, y, bmp, w, h, invert=False):
        bw = (w + 7) // 8
        for j in range(h):
            for i in range(w):
                byte_val = bmp[j * bw + i // 8]
                bit_val = 1 if (byte_val & (128 >> (i & 7))) else 0
                if bit_val:
                    self.drawPixel(x + i, y + j, 2 if invert else 1)

    def drawBitmap(self, x, y, bmp, w, h, invert=False, blink=1):
        icon_id = id(bmp)
        with self.scroll_lock:
            if icon_id in self._icons:
                old = self._icons[icon_id]
                self.drawRect(old['x'], old['y'], old['x'] + old['w'] - 1, old['y'] + old['h'] - 1, fill=True, color=0)
                
            if blink == 0:
                if icon_id in self._icons:
                    del self._icons[icon_id]
            else:
                self._icons[icon_id] = {
                    'x': x, 'y': y, 'bmp': bmp, 'w': w, 'h': h, 
                    'invert': invert, 'blink': blink, 'visible': True
                }
                self._renderBitmap(x, y, bmp, w, h, invert)
                
            if blink == 2 and not self._blink_thread_started:
                self._blink_thread_started = True
                threading.Thread(target=self._blink_loop, daemon=True).start()

    def drawIcon(self, x, y, icon_name, blink=1):
        icons = getattr(self.__class__, "Icons", {})
        if icon_name in icons:
            self.drawBitmap(x, y, icons[icon_name], 8, 8, blink=blink)


    def drawChar(self, x, y, c, size=5, invert=False, micro=False):
        if micro:
            if c not in FontMicro:
                return
            font_data = FontMicro[c]
            # Микро шрифт 3x5
            for i in range(3):
                line = font_data[i]
                for j in range(5):
                    pix = line & 0x01
                    if invert:
                        pix = not pix
                    self.drawPixel(x + i, y + j, 1 if pix else 0)
                    line >>= 1
            return

        if c in FontUKR:
            font_data = FontUKR[c]
        else:
            idx = ord(c) - ord(' ')
            if idx < 0 or idx >= len(Font0508):
                return
            font_data = Font0508[idx]
            
        for i in range(5):
            line = font_data[i]
            for j in range(8):
                pix = line & 0x01
                if invert:
                    pix = not pix
                self.drawPixel(x + i, y + j, 1 if pix else 0)
                line >>= 1

    def drawString(self, x, y, string, size=5, invert=False, wrap=True, micro=False):
        advance = 4 if micro else 6 # для micro ширина 3 + 1 пробел = 4
        char_height = 6 if micro else size
        orig_x = x
        for c in string:
            if wrap and x > (self.WIDTH - advance):
                x = 0
                y += char_height
                if y > (self.HEIGHT - char_height):
                    y = 0
            self.drawChar(x, y, c, size, invert, micro)
            x += advance

    def drawStringRun(self, string, y, speed, runs):
        """
        Scrolls the string from right to left smoothly.
        speed: pixels per second.
        """
        run_delay = 1.0
        text_w = len(string) * 6

        with self.run_lock:
            for r in range(runs):
                x = float(self.WIDTH)
                last_time = time.time()
                
                while x > -text_w:
                    curr_x = int(x)
                    with self.scroll_lock:
                        # Clear only the row area the text occupies
                        self.drawRect(0, y, self.WIDTH - 1, y + 7, fill=True, color=0)
                        self.drawString(curr_x, y, string, wrap=False)
                        self.display()
                    
                    now = time.time()
                    dt = now - last_time
                    
                    # Prevent 100% CPU usage / define max framerate (e.g. 60fps)
                    target_dt = 1.0 / 60.0
                    if dt < target_dt:
                        time.sleep(target_dt - dt)
                        now = time.time()
                        dt = now - last_time
                        
                    x -= speed * dt
                    last_time = now
                
                with self.scroll_lock:
                    # Clear string completely once run is done
                    self.drawRect(0, y, self.WIDTH - 1, y + 7, fill=True, color=0)
                    self.display()
                time.sleep(run_delay)

    def display(self):
        for page in range(self.PAGES):
            # Hardware is physically wired to a 64x32 grid starting at 
            # column 32 and page 1 in the 128x64 controller RAM.
            self.command(0xB0 + page + 1)
            self.command(0x00) # 32 & 0x0F = 0x00
            self.command(0x12) # (32 >> 4) | 0x10 = 0x12
            # Try writing in a block for faster execution instead of byte by byte!
            start_index = page * self.WIDTH
            end_index = start_index + self.WIDTH
            data_to_write = list(self.buffer[start_index:end_index])
            
            # Write up to 32 bytes at a time
            for chunk_offset in range(0, len(data_to_write), 32):
                chunk = data_to_write[chunk_offset:chunk_offset+32]
                try:
                    self.bus.write_i2c_block_data(self.addr, 0x40, chunk)
                except OSError:
                    pass
